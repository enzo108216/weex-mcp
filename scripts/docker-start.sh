#!/bin/sh
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
ENV_FILE=${WEEX_MCP_ENV_FILE:-"$PROJECT_ROOT/.env"}
START_TIMEOUT=${WEEX_MCP_START_TIMEOUT_SECONDS:-120}
MCP_PORT=${WEEX_MCP_PORT:-}
HOST_PORT=${WEEX_MCP_HOST_PORT:-}
BIND_HOST=${WEEX_MCP_BIND_HOST:-}
CONTAINER_UID=${WEEX_MCP_CONTAINER_UID:-}
CONTAINER_GID=${WEEX_MCP_CONTAINER_GID:-}

if [ -e "$ENV_FILE" ]; then
    if [ -z "$MCP_PORT" ]; then
        MCP_PORT=$(awk -F= '$1 == "WEEX_MCP_PORT" {print $2; exit}' "$ENV_FILE")
    fi
    if [ -z "$HOST_PORT" ]; then
        HOST_PORT=$(awk -F= '$1 == "WEEX_MCP_HOST_PORT" {print $2; exit}' "$ENV_FILE")
    fi
    if [ -z "$BIND_HOST" ]; then
        BIND_HOST=$(awk -F= '$1 == "WEEX_MCP_BIND_HOST" {print $2; exit}' "$ENV_FILE")
    fi
    if [ -z "$CONTAINER_UID" ]; then
        CONTAINER_UID=$(awk -F= '$1 == "WEEX_MCP_CONTAINER_UID" {print $2; exit}' "$ENV_FILE")
    fi
    if [ -z "$CONTAINER_GID" ]; then
        CONTAINER_GID=$(awk -F= '$1 == "WEEX_MCP_CONTAINER_GID" {print $2; exit}' "$ENV_FILE")
    fi
fi
MCP_PORT=${MCP_PORT:-8080}
HOST_PORT=${HOST_PORT:-8080}
BIND_HOST=${BIND_HOST:-127.0.0.1}
CONTAINER_UID=${CONTAINER_UID:-$(id -u)}
CONTAINER_GID=${CONTAINER_GID:-$(id -g)}

generate_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 32
        return
    fi
    if command -v python3 >/dev/null 2>&1; then
        python3 -c 'import secrets; print(secrets.token_hex(32))'
        return
    fi
    printf '%s\n' 'docker-start: openssl or python3 is required to generate local service secrets.' >&2
    exit 1
}

if ! command -v docker >/dev/null 2>&1; then
    printf '%s\n' 'docker-start: Docker is not installed or is not on PATH.' >&2
    exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
    printf '%s\n' 'docker-start: Docker Compose v2 is required.' >&2
    exit 1
fi
mkdir -p "$PROJECT_ROOT/logs"

if [ ! -e "$ENV_FILE" ]; then
    ENV_DIR=$(dirname -- "$ENV_FILE")
    if [ ! -d "$ENV_DIR" ]; then
        mkdir -p "$ENV_DIR"
    fi
    APPROVAL_SECRET=$(generate_secret)
    SERVICE_TOKEN=$(generate_secret)
    umask 077
    {
        printf '%s\n' '# Generated by scripts/docker-start.sh. Keep this file private.'
        printf 'WEEX_APPROVAL_TOKEN_SECRET=%s\n' "$APPROVAL_SECRET"
        printf 'WEEX_SERVICE_AUTH_TOKEN=%s\n' "$SERVICE_TOKEN"
        printf '%s\n' 'WEEX_TRADE_ENABLED=false'
        printf 'WEEX_MCP_PORT=%s\n' "$MCP_PORT"
        printf 'WEEX_MCP_HOST_PORT=%s\n' "$HOST_PORT"
        printf 'WEEX_MCP_BIND_HOST=%s\n' "$BIND_HOST"
        printf '%s\n' 'WEEX_AUDIT_LOG_FILE=/var/log/weex-mcp/weex_mcp_audit.log'
        printf 'WEEX_MCP_CONTAINER_UID=%s\n' "$CONTAINER_UID"
        printf 'WEEX_MCP_CONTAINER_GID=%s\n' "$CONTAINER_GID"
    } >"$ENV_FILE"
    chmod 600 "$ENV_FILE"
    printf 'Created private Docker configuration: %s\n' "$ENV_FILE"
else
    printf 'Using existing Docker configuration: %s\n' "$ENV_FILE"
fi

WEEX_MCP_ENV_FILE="$ENV_FILE" \
WEEX_MCP_CONTAINER_UID="$CONTAINER_UID" \
WEEX_MCP_CONTAINER_GID="$CONTAINER_GID" \
docker compose \
    --project-directory "$PROJECT_ROOT" \
    --env-file "$ENV_FILE" \
    up --detach --build --wait --wait-timeout "$START_TIMEOUT"

ACCESS_HOST=$BIND_HOST
if [ "$ACCESS_HOST" = "0.0.0.0" ]; then
    ACCESS_HOST=127.0.0.1
fi
printf 'WEEX MCP is published on %s:%s.\n' "$BIND_HOST" "$HOST_PORT"
printf 'Readiness: http://%s:%s/readyz\n' "$ACCESS_HOST" "$HOST_PORT"
printf 'MCP endpoint: http://%s:%s/mcp; its bearer token remains in %s.\n' "$ACCESS_HOST" "$HOST_PORT" "$ENV_FILE"
